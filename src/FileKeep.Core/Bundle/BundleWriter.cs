using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using FileKeep.Core.Json;

namespace FileKeep.Core.Bundle;

/// <summary>
/// Creates "FileKeep offline bundle v1" packages.
/// Shared between the desktop exporter and the iOS secure workspace.
/// </summary>
public static class BundleWriter
{
	public const string ExpectedFormat = "FileKeep offline bundle v1";
	private static readonly byte[] Magic = Encoding.ASCII.GetBytes("FKBO");

	/// <summary>
	/// Builds fresh bundle bytes from a header (format + wraps),
	/// the DEK, and the complete file list. Every file gets a fresh nonce.
	/// </summary>
	public static byte[] Rebuild(BundleHeader header, byte[] dek, IReadOnlyList<(string Path, byte[] Plaintext)> files)
	{
		ArgumentNullException.ThrowIfNull(header);
		ArgumentNullException.ThrowIfNull(dek);
		ArgumentNullException.ThrowIfNull(files);
		if (dek.Length != KeyDerivation.KeySizeBytes)
			throw new ArgumentException($"DEK must be {KeyDerivation.KeySizeBytes} bytes.", nameof(dek));

		// Encrypt each file with a fresh nonce.
		var segments = new List<byte[]>(files.Count);
		var entries = new List<BundleFileEntry>(files.Count);
		foreach (var (path, plaintext) in files)
		{
			if (string.IsNullOrWhiteSpace(path))
				throw new ArgumentException("File path must not be empty.", nameof(files));
			ArgumentNullException.ThrowIfNull(plaintext);

			byte[] nonce = RandomNumberGenerator.GetBytes(ChunkCrypto.NonceSizeBytes);
			byte[] ciphertext = AesGcmEncrypt(dek, nonce, plaintext);
			segments.Add(ciphertext);
			entries.Add(new BundleFileEntry
			{
				Path = path,
				Size = plaintext.Length,
				ModifiedUtc = DateTimeOffset.UtcNow,
				NonceB64 = Convert.ToBase64String(nonce),
				Offset = 0, // patched below
				Length = ciphertext.Length,
			});
		}

		var newHeader = new BundleHeader
		{
			Format = ExpectedFormat,
			Wraps = header.Wraps,
			Totp = header.Totp,
			Files = entries,
		};

		// Offsets are absolute from bundle start and depend on the serialized
		// header length; iterate to a fixed point (converges in 1-2 passes).
		var offsets = new long[entries.Count];
		byte[] blob = Array.Empty<byte>();
		for (int pass = 0; pass < 5; pass++)
		{
			for (int i = 0; i < entries.Count; i++)
				entries[i].Offset = offsets[i];
			byte[] headerJson = JsonSerializer.SerializeToUtf8Bytes(newHeader, FileKeepJsonContext.Default.BundleHeader);
			blob = new byte[8 + headerJson.Length + TotalLength(segments)];
			Encoding.ASCII.GetBytes("FKBO").CopyTo(blob, 0);
			BitConverter.GetBytes(headerJson.Length).CopyTo(blob, 4);
			headerJson.CopyTo(blob, 8);

			long pos = 8 + headerJson.Length;
			bool stable = true;
			for (int i = 0; i < segments.Count; i++)
			{
				if (offsets[i] != pos)
					stable = false;
				offsets[i] = pos;
				segments[i].CopyTo(blob, (int)pos);
				pos += segments[i].Length;
			}
			if (stable)
				break;
		}

		return blob;
	}

	/// <summary>
	/// Creates a new bundle from scratch: fresh DEK is generated by the caller,
	/// wraps are built via <see cref="CreateWrap"/>, files are encrypted.
	/// </summary>
	public static byte[] Create(
		IReadOnlyList<BundleWrap> wraps,
		byte[] dek,
		IReadOnlyList<(string Path, byte[] Plaintext)> files)
	{
		ArgumentNullException.ThrowIfNull(wraps);
		var header = new BundleHeader
		{
			Format = ExpectedFormat,
			Wraps = new List<BundleWrap>(wraps),
		};
		return Rebuild(header, dek, files);
	}

	/// <summary>
	/// Creates a new BundleWrap by AES-256-GCM encrypting the given plaintext
	/// (a DEK or a share) with the KEK. The caller supplies method-specific
	/// fields (salt/iterations for passphrase, slot/challenge for YubiKey).
	/// </summary>
	public static BundleWrap CreateWrap(
		string type,
		byte[] kek,
		byte[] plaintext,
		string? mode = null,
		string? group = null,
		byte[]? salt = null,
		int? iterations = null,
		int? slot = null,
		byte[]? challenge = null)
	{
		ArgumentNullException.ThrowIfNull(kek);
		ArgumentNullException.ThrowIfNull(plaintext);
		if (kek.Length != KeyDerivation.KeySizeBytes)
			throw new ArgumentException($"KEK must be {KeyDerivation.KeySizeBytes} bytes.", nameof(kek));

		byte[] nonce = RandomNumberGenerator.GetBytes(ChunkCrypto.NonceSizeBytes);
		byte[] data = AesGcmEncrypt(kek, nonce, plaintext);

		return new BundleWrap
		{
			Type = type,
			Mode = mode,
			Group = group,
			SaltB64 = salt is not null ? Convert.ToBase64String(salt) : null,
			Iterations = iterations,
			Slot = slot,
			ChallengeB64 = challenge is not null ? Convert.ToBase64String(challenge) : null,
			NonceB64 = Convert.ToBase64String(nonce),
			DataB64 = Convert.ToBase64String(data),
		};
	}

	private static long TotalLength(List<byte[]> segments)
	{
		long total = 0;
		foreach (var s in segments)
			total += s.Length;
		return total;
	}

	/// <summary>data = ciphertext || tag.</summary>
	private static byte[] AesGcmEncrypt(byte[] key, byte[] nonce, byte[] plaintext)
	{
		byte[] ciphertext = new byte[plaintext.Length];
		byte[] tag = new byte[ChunkCrypto.TagSizeBytes];
		using var gcm = new AesGcm(key, ChunkCrypto.TagSizeBytes);
		gcm.Encrypt(nonce, plaintext, ciphertext, tag);
		byte[] out_ = new byte[ciphertext.Length + tag.Length];
		ciphertext.CopyTo(out_, 0);
		tag.CopyTo(out_, ciphertext.Length);
		CryptographicOperations.ZeroMemory(ciphertext);
		return out_;
	}
}
